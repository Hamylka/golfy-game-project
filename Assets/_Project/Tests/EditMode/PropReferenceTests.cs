using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Text;
using IsoGolf.Generation;
using NUnit.Framework;
using Debug = UnityEngine.Debug;

namespace IsoGolf.Tests
{
    /// <summary>
    /// F3.4 (split fairway plan §4): the props of every generated course, variant 0, seeds 0-49 of each par, hashed one value per
    /// prop by <see cref="CourseFingerprint.Prop"/>, so a later change can say which props moved, not only that some did.
    /// Two references: `PropReferenceBefore` on F3.3's code (before any F3.4 change), and
    /// `PropReferenceCapsuleFix` after the fork capsule fix, before the spine theme. The guards that read them are in
    /// `SpinePropTests`.
    /// </summary>
    public class PropReferenceTests
    {
        internal const int Seeds = 50;
        private const string Folder = "Assets/_Project/Tests/EditMode/";

        /// <summary>Writes `PropReferenceBefore`. Run by hand only on F3.3's code.</summary>
        [Test]
        [Explicit("Writes the reference file; run by hand only on the reference code")]
        [Timeout(1800000)]
        public void CapturePropReferenceBefore() => Capture("PropReferenceBefore", "on F3.3's code, before any F3.4 change");

        /// <summary>Writes `PropReferenceCapsuleFix`. Run by hand only on the capsule fix, before the spine theme.</summary>
        [Test]
        [Explicit("Writes the reference file; run by hand only on the reference code")]
        [Timeout(1800000)]
        public void CapturePropReferenceCapsuleFix() => Capture("PropReferenceCapsuleFix", "after the fork capsule fix, before the spine theme");

        /// <summary>The course's props, as the references store them: par, seed, 1 on a fork course (else 0), the count, then one hash per prop.</summary>
        internal static List<ulong> Row(int seed, int par, out CourseLayout layout)
        {
            layout = CourseGenerator.Generate(seed, par, CourseGeneratorTests.Settings);
            var row = new List<ulong> { (ulong)par, (ulong)seed, IsFork(layout) ? 1UL : 0UL, (ulong)layout.Props.Count };
            foreach (CourseProp prop in layout.Props)
            {
                row.Add(CourseFingerprint.Prop(prop));
            }

            return row;
        }

        internal static bool IsFork(CourseLayout layout)
        {
            if (layout.Plan != null)
            {
                foreach (FairwayShape shape in layout.Plan.FairwayShapes)
                {
                    if (shape.Kind == FairwayShapeKind.Fork)
                    {
                        return true;
                    }
                }
            }

            return false;
        }

        /// <summary>The reference's rows, keyed by (par, seed): fork flag, then the prop hashes in order.</summary>
        internal static Dictionary<(int, int), (bool fork, List<ulong> props)> Read(ulong[] data)
        {
            var rows = new Dictionary<(int, int), (bool, List<ulong>)>();
            int i = 0;
            while (i < data.Length)
            {
                int par = (int)data[i];
                int seed = (int)data[i + 1];
                bool fork = data[i + 2] != 0;
                int count = (int)data[i + 3];
                rows[(par, seed)] = (fork, new List<ulong>(new System.ArraySegment<ulong>(data, i + 4, count)));
                i += 4 + count;
            }

            return rows;
        }

        private static void Capture(string name, string when)
        {
            var clock = Stopwatch.StartNew();
            var rows = new StringBuilder();
            int props = 0;
            foreach (int par in new[] { 3, 4, 5 })
            {
                for (int seed = 0; seed < Seeds; seed++)
                {
                    List<ulong> row = Row(seed, par, out _);
                    rows.Append($"            {row[0]}UL, {row[1]}UL, {row[2]}UL, {row[3]}UL,");
                    for (int k = 4; k < row.Count; k++)
                    {
                        rows.Append($" 0x{row[k]:X16}UL,");
                    }

                    rows.AppendLine();
                    props += row.Count - 4;
                }
            }

            string commit = PlainCourseReferenceTestsGit.Commit();
            var text = new StringBuilder();
            text.AppendLine("// <auto-generated>");
            text.AppendLine($"// Generated by PropReferenceTests on commit {commit}, {when}.");
            text.AppendLine("// Do not edit by hand. Editor x64 Mono hashes: a regression guard, not a cross-platform proof.");
            text.AppendLine("// </auto-generated>");
            text.AppendLine("namespace IsoGolf.Tests");
            text.AppendLine("{");
            text.AppendLine($"    public static class {name}");
            text.AppendLine("    {");
            text.AppendLine($"        public const string Commit = \"{commit}\";");
            text.AppendLine();
            text.AppendLine("        /// <summary>Par, seed, 1 on a fork course, the prop count, then one hash per prop: variant 0, seeds 0-49 of each par.</summary>");
            text.AppendLine("        public static readonly ulong[] Courses =");
            text.AppendLine("        {");
            text.Append(rows);
            text.AppendLine("        };");
            text.AppendLine("    }");
            text.AppendLine("}");
            File.WriteAllText(Folder + name + ".cs", text.ToString());
            Debug.Log($"PROP_REFERENCE {name} captured {props} props on {3 * Seeds} courses in {clock.Elapsed.TotalSeconds:F1} s");
        }
    }
}
