using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Text;
using IsoGolf.Gameplay;
using IsoGolf.Generation;
using NUnit.Framework;
using Debug = UnityEngine.Debug;

namespace IsoGolf.Tests
{
    /// <summary>
    /// Strategic obstacles S1 (`feature/strategic-zones`): one hash per checked course (<see cref="CheckedCourse.Generate"/>), seeds
    /// 0-49 of each par, covering the kept variant, the candidates, the failed checks, the dropped-prop count and every kept prop
    /// (<see cref="CourseFingerprint.Prop"/>, in order). `CheckedCourseReferenceBefore` was captured on develop b3e4a8b, before any S1
    /// change: S1 places no strategic prop, so every checked course must still match it (`PlainCoursesBitIdentical`). S2 reuses it
    /// for `OtherPropsBitIdentical`, the spine aside.
    /// </summary>
    public class CheckedCourseReferenceTests
    {
        internal const int Seeds = 50;
        private const string Folder = "Assets/_Project/Tests/EditMode/";

        private const ulong Offset = 14695981039346656037UL;
        private const ulong Prime = 1099511628211UL;

        /// <summary>Writes `CheckedCourseReferenceBefore`. Run by hand only on the reference code (develop b3e4a8b).</summary>
        [Test]
        [Explicit("Writes the reference file; run by hand only on the reference code")]
        [Category("Reference")]
        public void CaptureCheckedReferenceBefore() => Capture("CheckedCourseReferenceBefore", "on develop b3e4a8b, before any strategic obstacles S1 change");

        /// <summary>The hash of one checked course: variant, candidates, failed checks, dropped props, prop count, every prop's hash.</summary>
        internal static ulong Hash(int seed, int par)
        {
            CheckedCourseResult result = CheckedCourse.Generate(seed, par, CourseGeneratorTests.Settings, CourseCheckMeasurements.Shot);
            return HashOf(result, result.Layout.Props, result.DroppedProps);
        }

        /// <summary>The same hash over a chosen set of the kept props and a dropped count (S2 leaves the strategic group out).</summary>
        internal static ulong HashOf(CheckedCourseResult result, IReadOnlyList<CourseProp> props, int dropped)
        {
            ulong hash = Offset;
            hash = Fold(hash, (ulong)result.Variant);
            hash = Fold(hash, (ulong)result.Candidates);
            hash = Fold(hash, (ulong)result.Failed);
            hash = Fold(hash, (ulong)dropped);
            hash = Fold(hash, (ulong)props.Count);
            foreach (CourseProp prop in props)
            {
                hash = Fold(hash, CourseFingerprint.Prop(prop));
            }

            return hash;
        }

        private static ulong Fold(ulong hash, ulong value)
        {
            for (int b = 0; b < 8; b++)
            {
                hash ^= (value >> (8 * b)) & 0xFF;
                hash *= Prime;
            }

            return hash;
        }

        private static void Capture(string name, string when)
        {
            var clock = Stopwatch.StartNew();
            var rows = new StringBuilder();
            foreach (int par in new[] { 3, 4, 5 })
            {
                rows.Append("            ");
                for (int seed = 0; seed < Seeds; seed++)
                {
                    rows.Append($"0x{Hash(seed, par):X16}UL,");
                    rows.Append(seed % 5 == 4 ? "\n            " : " ");
                }

                rows.AppendLine();
            }

            string commit = PlainCourseReferenceTestsGit.Commit();
            var text = new StringBuilder();
            text.AppendLine("// <auto-generated>");
            text.AppendLine($"// Generated by CheckedCourseReferenceTests.CaptureCheckedReferenceBefore on commit {commit}, {when}.");
            text.AppendLine("// One hash per checked course (variant, candidates, failed checks, dropped props, every prop), seeds 0-49 of par 3, 4, 5 in order.");
            text.AppendLine("// S1 (PlainCoursesBitIdentical) and S2 (OtherPropsBitIdentical) compare against it.");
            text.AppendLine("// Do not edit by hand. Editor x64 Mono hashes: a regression guard, not a cross-platform proof.");
            text.AppendLine("// </auto-generated>");
            text.AppendLine("namespace IsoGolf.Tests");
            text.AppendLine("{");
            text.AppendLine($"    public static class {name}");
            text.AppendLine("    {");
            text.AppendLine($"        public const string Commit = \"{commit}\";");
            text.AppendLine();
            text.AppendLine("        /// <summary>Checked course hashes: seeds 0-49 of par 3, then par 4, then par 5.</summary>");
            text.AppendLine("        public static readonly ulong[] Courses =");
            text.AppendLine("        {");
            text.Append(rows.ToString().Replace("            \n", string.Empty));
            text.AppendLine("        };");
            text.AppendLine("    }");
            text.AppendLine("}");
            File.WriteAllText(Folder + name + ".cs", text.ToString());
            Debug.Log($"CHECKED_REFERENCE {name} captured {3 * Seeds} courses in {clock.Elapsed.TotalSeconds:F1} s");
        }
    }
}
