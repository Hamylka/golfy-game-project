using System.Diagnostics;
using System.IO;
using System.Text;
using IsoGolf.Gameplay;
using IsoGolf.Generation;
using NUnit.Framework;
using UnityEditor;
using UnityEngine;
using Debug = UnityEngine.Debug;

namespace IsoGolf.Tests
{
    /// <summary>
    /// F3.1 (split fairway plan §2, §7): the fairway became pieces in the centreline's frame plus rough ovals, and a plain course is
    /// one piece. Every plain course must stay bit-identical to what `develop` built before the change: its fields on a grid, its
    /// terrain mesh and its layout, hashed by <see cref="CourseFingerprint"/> and compared with <see cref="PlainCourseReference"/>,
    /// which was captured on the unchanged code. Courses come from <see cref="CheckedCourse"/>, as `Main` plays them.
    /// </summary>
    public class PlainCourseReferenceTests
    {
        public const int ReferenceSeeds = 200;

        private const string ReferencePath = "Assets/_Project/Tests/EditMode/PlainCourseReference.cs";

        private static PaletteSettings Palette => AssetDatabase.LoadAssetAtPath<PaletteSettings>("Assets/_Project/Settings/Palette.asset");

        // About 0.6 s a course in the Editor (the terrain build is most of it), so about 90 s for seeds 0-49.
        [Test]
        [Timeout(600000)]
        public void PlainCoursesAreBitIdentical() => Check(50);

        [Test]
        [Explicit("Full sweep, seeds 0-199: run by hand when a PR changes the fairway rules and the director asks")]
        [Timeout(1800000)]
        public void PlainCoursesAreBitIdentical_FullSweep() => Check(ReferenceSeeds);

        /// <summary>
        /// Writes <see cref="PlainCourseReference"/>. The only thing that writes it: run by hand on code whose plain courses are the
        /// reference (F3.1: `develop` before the change), never to make a failing check pass.
        /// </summary>
        [Test]
        [Explicit("Writes the reference file; run by hand only on the reference code")]
        [Timeout(1800000)]
        public void CapturePlainCourseReference()
        {
            var clock = Stopwatch.StartNew();
            var text = new StringBuilder();
            text.AppendLine("// <auto-generated>");
            text.AppendLine($"// Generated by PlainCourseReferenceTests.CapturePlainCourseReference on commit {GitCommit()}, before the F3.1 fairway pieces.");
            text.AppendLine("// Do not edit by hand. Editor x64 Mono hashes: a regression guard, not a cross-platform proof.");
            text.AppendLine("// </auto-generated>");
            text.AppendLine("namespace IsoGolf.Tests");
            text.AppendLine("{");
            text.AppendLine("    public static class PlainCourseReference");
            text.AppendLine("    {");
            text.AppendLine($"        public const string Commit = \"{GitCommit()}\";");
            text.AppendLine();
            text.AppendLine("        /// <summary>Fields, mesh and layout hashes, three per course, index ((par - 3) * 200 + seed) * 3.</summary>");
            text.AppendLine("        public static readonly ulong[] Generated =");
            text.AppendLine("        {");
            foreach (int par in new[] { 3, 4, 5 })
            {
                for (int seed = 0; seed < ReferenceSeeds; seed++)
                {
                    ulong[] h = Generated(seed, par);
                    text.AppendLine($"            0x{h[0]:X16}UL, 0x{h[1]:X16}UL, 0x{h[2]:X16}UL, // par {par} seed {seed}");
                }
            }

            text.AppendLine("        };");
            text.AppendLine();
            text.AppendLine("        /// <summary>The hand-made courses, in the order of <see cref=\"CameraCourse.ScenePaths\"/>, three hashes each.</summary>");
            text.AppendLine("        public static readonly ulong[] Fixtures =");
            text.AppendLine("        {");
            foreach (string path in CameraCourse.ScenePaths)
            {
                ulong[] h = Fixture(path);
                text.AppendLine($"            0x{h[0]:X16}UL, 0x{h[1]:X16}UL, 0x{h[2]:X16}UL, // {Path.GetFileNameWithoutExtension(path)}");
            }

            text.AppendLine("        };");
            text.AppendLine("    }");
            text.AppendLine("}");
            File.WriteAllText(ReferencePath, text.ToString());
            Debug.Log($"PLAIN_REFERENCE captured {3 * ReferenceSeeds} generated courses and {CameraCourse.ScenePaths.Length} fixtures in {clock.Elapsed.TotalSeconds:F1} s");
        }

        private static void Check(int seeds)
        {
            Assert.That(PlainCourseReference.Generated.Length, Is.EqualTo(3 * ReferenceSeeds * 3), "The reference is not captured.");
            var clock = Stopwatch.StartNew();
            var failures = new StringBuilder();
            foreach (int par in new[] { 3, 4, 5 })
            {
                for (int seed = 0; seed < seeds; seed++)
                {
                    int index = (((par - 3) * ReferenceSeeds) + seed) * 3;
                    Compare(failures, $"par {par} seed {seed}", Generated(seed, par), PlainCourseReference.Generated, index);
                }
            }

            for (int i = 0; i < CameraCourse.ScenePaths.Length; i++)
            {
                Compare(failures, CameraCourse.ScenePaths[i], Fixture(CameraCourse.ScenePaths[i]), PlainCourseReference.Fixtures, i * 3);
            }

            Debug.Log($"PLAIN_REFERENCE checked seeds 0-{seeds - 1} on every par and {CameraCourse.ScenePaths.Length} fixtures in {clock.Elapsed.TotalSeconds:F1} s");
            Assert.That(failures.Length, Is.Zero, failures.ToString());
        }

        private static void Compare(StringBuilder failures, string name, ulong[] actual, ulong[] reference, int index)
        {
            string[] parts = { "fields", "mesh", "layout" };
            for (int i = 0; i < 3; i++)
            {
                if (actual[i] != reference[index + i])
                {
                    failures.AppendLine($"{name}: {parts[i]} differ from the reference ({PlainCourseReference.Commit})");
                }
            }
        }

        private static ulong[] Generated(int seed, int par)
        {
            CheckedCourseResult result = CheckedCourse.Generate(seed, par, CourseGeneratorTests.Settings, CourseCheckMeasurements.Shot);
            CourseLayout layout = result.Layout;
            return new[]
            {
                CourseFingerprint.Fields(layout),
                CourseFingerprint.Mesh(layout, Palette),
                CourseFingerprint.Layout(layout, result.Variant, result.Candidates, result.DroppedProps),
            };
        }

        private static ulong[] Fixture(string path)
        {
            CourseLayout layout = AssetDatabase.LoadAssetAtPath<CourseShapeSettings>(path).ToLayout();
            return new[] { CourseFingerprint.Fields(layout), CourseFingerprint.Mesh(layout, Palette), CourseFingerprint.Layout(layout, 0, 0, 0) };
        }

        private static string GitCommit()
        {
            try
            {
                var start = new ProcessStartInfo("git", "rev-parse --short HEAD")
                {
                    RedirectStandardOutput = true,
                    UseShellExecute = false,
                    CreateNoWindow = true,
                    WorkingDirectory = Path.GetDirectoryName(Application.dataPath),
                };
                using Process process = Process.Start(start);
                string output = process.StandardOutput.ReadToEnd().Trim();
                process.WaitForExit();
                return output.Length > 0 ? output : "unknown";
            }
            catch (System.Exception)
            {
                return "unknown";
            }
        }
    }
}
