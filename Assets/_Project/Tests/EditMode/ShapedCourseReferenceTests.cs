using System.Diagnostics;
using System.IO;
using System.Text;
using IsoGolf.Gameplay;
using IsoGolf.Generation;
using NUnit.Framework;
using Debug = UnityEngine.Debug;

namespace IsoGolf.Tests
{
    /// <summary>
    /// F3.3 (split fairway plan §5): forks must leave F3.2's rough islands and splits bit for bit. Every checked course that tried a
    /// rough island or a split on some variant, and drew no fork on any variant the checks tried, is hashed by
    /// <see cref="CourseFingerprint"/> and compared with <see cref="ShapedCourseReference"/>, captured on F3.2's code (`develop`
    /// 81b0ce9) in a commit of its own, before the forks. Plain courses stay with <see cref="PlainCourseReferenceTests"/>.
    /// </summary>
    public class ShapedCourseReferenceTests
    {
        private const string ReferencePath = "Assets/_Project/Tests/EditMode/ShapedCourseReference.cs";

        [Test]
        [Timeout(900000)]
        public void RoughIslandsAndSplitsAreBitIdentical() => Check(50);

        [Test]
        [Explicit("Full sweep, seeds 0-199: run by hand when a PR changes the fairway rules and the director asks")]
        [Timeout(1800000)]
        public void RoughIslandsAndSplitsAreBitIdentical_FullSweep() => Check(PlainCourseReferenceTests.ReferenceSeeds);

        /// <summary>Writes <see cref="ShapedCourseReference"/>. Run by hand only on the reference code (F3.2, before the forks).</summary>
        [Test]
        [Explicit("Writes the reference file; run by hand only on the reference code")]
        [Timeout(3600000)]
        public void CaptureShapedCourseReference()
        {
            var clock = Stopwatch.StartNew();
            var rows = new StringBuilder();
            int count = 0;
            foreach (int par in new[] { 3, 4, 5 })
            {
                for (int seed = 0; seed < PlainCourseReferenceTests.ReferenceSeeds; seed++)
                {
                    CheckedCourseResult result = CheckedCourse.Generate(seed, par, CourseGeneratorTests.Settings, CourseCheckMeasurements.Shot);
                    if (!Compared(seed, par, result))
                    {
                        continue;
                    }

                    ulong[] h = PlainCourseReferenceTests.Hashes(result);
                    rows.AppendLine($"            {par}UL, {seed}UL, 0x{h[0]:X16}UL, 0x{h[1]:X16}UL, 0x{h[2]:X16}UL,");
                    count++;
                }
            }

            string commit = PlainCourseReferenceTestsGit.Commit();
            var text = new StringBuilder();
            text.AppendLine("// <auto-generated>");
            text.AppendLine($"// Generated by ShapedCourseReferenceTests.CaptureShapedCourseReference on commit {commit}, before the F3.3 forks.");
            text.AppendLine("// Do not edit by hand. Editor x64 Mono hashes: a regression guard, not a cross-platform proof.");
            text.AppendLine("// </auto-generated>");
            text.AppendLine("namespace IsoGolf.Tests");
            text.AppendLine("{");
            text.AppendLine("    public static class ShapedCourseReference");
            text.AppendLine("    {");
            text.AppendLine($"        public const string Commit = \"{commit}\";");
            text.AppendLine();
            text.AppendLine("        /// <summary>Par, seed, then the fields, mesh and layout hashes: five values per shaped course with no fork tried.</summary>");
            text.AppendLine("        public static readonly ulong[] Courses =");
            text.AppendLine("        {");
            text.Append(rows);
            text.AppendLine("        };");
            text.AppendLine("    }");
            text.AppendLine("}");
            File.WriteAllText(ReferencePath, text.ToString());
            Debug.Log($"SHAPED_REFERENCE captured {count} shaped courses in {clock.Elapsed.TotalSeconds:F1} s");
        }

        /// <summary>A course this guard compares: some variant the checks tried carries a shape, and none drew a fork.</summary>
        internal static bool Compared(int seed, int par, CheckedCourseResult result)
        {
            bool shaped = false;
            for (int variant = 0; variant < result.Candidates; variant++)
            {
                CourseLayout layout = CourseGenerator.GenerateBare(seed, par, CourseGeneratorTests.Settings, variant, out FairwayShapeResult shapes);
                if (shapes.FirstDrawn == FairwayShapeKind.Fork || shapes.SecondDrawn == FairwayShapeKind.Fork)
                {
                    return false;
                }

                shaped |= layout.Plan.FairwayShapes.Count > 0;
            }

            return shaped;
        }

        private static void Check(int seeds)
        {
            ulong[] reference = ShapedCourseReference.Courses;
            Assert.That(reference.Length, Is.GreaterThan(0), "The reference is not captured.");
            var clock = Stopwatch.StartNew();
            var failures = new StringBuilder();
            string[] parts = { "fields", "mesh", "layout" };
            int compared = 0, nowForks = 0;
            for (int i = 0; i < reference.Length; i += 5)
            {
                int par = (int)reference[i], seed = (int)reference[i + 1];
                if (seed >= seeds)
                {
                    continue;
                }

                CheckedCourseResult result = CheckedCourse.Generate(seed, par, CourseGeneratorTests.Settings, CourseCheckMeasurements.Shot);

                // F3.3's fork weights take plain's range from its top: a par 5 whose other draw (the first or the second shape's)
                // was plain may now draw a fork, which is a fork course, no longer one this guard compares.
                if (!Compared(seed, par, result))
                {
                    nowForks++;
                    continue;
                }

                ulong[] h = PlainCourseReferenceTests.Hashes(result);
                for (int k = 0; k < 3; k++)
                {
                    if (h[k] != reference[i + 2 + k])
                    {
                        failures.AppendLine($"par {par} seed {seed}: {parts[k]} differ from the reference ({ShapedCourseReference.Commit})");
                    }
                }

                compared++;
            }

            Debug.Log($"SHAPED_REFERENCE compared {compared} shaped courses (seeds 0-{seeds - 1}), {nowForks} now drawing a fork skipped, in {clock.Elapsed.TotalSeconds:F1} s");
            Assert.That(compared, Is.GreaterThan(0));
            Assert.That(failures.Length, Is.Zero, failures.ToString());
        }
    }

    /// <summary>The short commit of the checkout, for the reference files' headers.</summary>
    internal static class PlainCourseReferenceTestsGit
    {
        public static string Commit()
        {
            try
            {
                var start = new ProcessStartInfo("git", "rev-parse --short HEAD")
                {
                    RedirectStandardOutput = true,
                    UseShellExecute = false,
                    CreateNoWindow = true,
                    WorkingDirectory = Path.GetDirectoryName(UnityEngine.Application.dataPath),
                };
                using Process process = Process.Start(start);
                string output = process.StandardOutput.ReadToEnd().Trim();
                process.WaitForExit();
                return output.Length > 0 ? output : "unknown";
            }
            catch (System.Exception)
            {
                return "unknown";
            }
        }
    }
}
